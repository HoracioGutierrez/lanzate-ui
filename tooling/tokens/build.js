// Builds every design-token output from tokens/ (DTCG JSON).
// See docs/architecture/tokens.md
//
//   node tooling/tokens/build.js          write the outputs
//   node tooling/tokens/build.js --check  exit 1 if any output is out of date
//
// Token paths follow `<scope>.<kind>.<name…>`:
//   scope  registry → shipped to consumers in the lanzate-theme registry item
//          site     → used by this website only (the standard shadcn set)
//   kind   color → `--<name>` per mode (:root / .dark), plus `--color-<name>` in @theme inline
//          theme → `--<name>` in @theme inline (so Tailwind makes a utility of it)
//          root  → `--<name>` on :root

import { readFile, readdir, writeFile, mkdir } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import StyleDictionary from "style-dictionary"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const TOKENS = path.join(ROOT, "tokens")
const OUT = path.join(ROOT, "src/styles/generated")
const REGISTRY_JSON = path.join(ROOT, "registry.json")
const THEME_ITEM = "lanzate-theme"
const HEADER = "Generated by tooling/tokens/build.js from tokens/. Do not edit; run `bun run tokens`."

const rel = (...parts) => path.join(TOKENS, ...parts)
const PRIMITIVES = (await readdir(rel("primitives"))).map((f) => rel("primitives", f))
const COMPONENTS = (await readdir(rel("component"))).map((f) => rel("component", f))
const THEMES = (await readdir(rel("themes"))).map((f) => rel("themes", f))
const LIGHT = rel("semantic/color.light.json")
const DARK = rel("semantic/color.dark.json")
const MODELESS = rel("semantic/theme.json")

async function loadTokens(sources) {
  const sd = new StyleDictionary({
    source: sources,
    usesDtcg: true,
    log: { verbosity: "silent", warnings: "disabled" },
    platforms: { css: { transforms: [] } },
  })
  const { allTokens } = await sd.getPlatformTokens("css")
  return allTokens
    .filter((t) => t.path[0] === "registry" || t.path[0] === "site")
    .map((t) => ({
      scope: t.path[0],
      kind: t.path[1],
      name: t.path.slice(2).join("-"),
      value: String(t.$value),
      file: path.resolve(t.filePath),
      intent: t.$extensions?.lanzate?.intent === true,
    }))
}

function fail(message) {
  console.error(`tokens: ${message}`)
  process.exit(1)
}

// ── Load ────────────────────────────────────────────────────────────────────
const base = await loadTokens([...PRIMITIVES, LIGHT, MODELESS, ...COMPONENTS])
const dark = (await loadTokens([...PRIMITIVES, LIGHT, DARK])).filter((t) => t.file === DARK)
const themes = await Promise.all(
  THEMES.map(async (file) => ({
    name: path.basename(file, ".json"),
    tokens: (await loadTokens([...PRIMITIVES, LIGHT, file])).filter((t) => t.file === file),
  })),
)

const colors = base.filter((t) => t.kind === "color")
const themeVars = base.filter((t) => t.kind === "theme")
const rootVars = base.filter((t) => t.kind === "root")

// ── Validate ────────────────────────────────────────────────────────────────
for (const t of base) {
  if (!["color", "theme", "root"].includes(t.kind)) fail(`unknown kind '${t.kind}' in ${t.scope}.${t.kind}.${t.name}`)
}
const lightNames = new Set(colors.map((t) => t.name))
const darkNames = new Set(dark.map((t) => t.name))
for (const n of lightNames) if (!darkNames.has(n)) fail(`color '${n}' has no dark value in color.dark.json`)
for (const n of darkNames) if (!lightNames.has(n)) fail(`color '${n}' is in color.dark.json but not color.light.json`)
for (const theme of themes) {
  for (const t of theme.tokens) {
    if (t.kind !== "color" || !lightNames.has(t.name)) fail(`theme '${theme.name}' overrides unknown color '${t.name}'`)
  }
}
for (const t of colors.filter((c) => c.intent)) {
  if (!lightNames.has(`${t.name}-foreground`)) fail(`intent color '${t.name}' needs a '${t.name}-foreground' token`)
}
const allVarNames = [...colors, ...themeVars, ...rootVars].map((t) => (t.kind === "color" ? t.name : t.name))
const duplicates = allVarNames.filter((n, i) => allVarNames.indexOf(n) !== i)
if (duplicates.length) fail(`duplicate variable names: ${[...new Set(duplicates)].join(", ")}`)

// ── Outputs ─────────────────────────────────────────────────────────────────
const decl = (name, value) => `  --${name}: ${value};`
const block = (selector, lines) => `${selector} {\n${lines.join("\n")}\n}`

function themeLines(tokens) {
  return [
    ...tokens.filter((t) => t.kind === "color").map((t) => decl(`color-${t.name}`, `var(--${t.name})`)),
    ...tokens.filter((t) => t.kind === "theme").map((t) => decl(t.name, t.value)),
  ]
}

const css = [
  `/* ${HEADER} */`,
  "",
  block("@theme inline", themeLines([...colors, ...themeVars])),
  "",
  block(":root", [...colors, ...rootVars].map((t) => decl(t.name, t.value))),
  "",
  block(".dark", dark.map((t) => decl(t.name, t.value))),
  ...themes.flatMap((theme) => ["", block(`.theme-${theme.name}`, theme.tokens.map((t) => decl(t.name, t.value)))]),
  "",
].join("\n")

const union = (names) => (names.length ? names.map((n) => JSON.stringify(n)).join(" | ") : "never")
const suffixes = (prefix) => themeVars.filter((t) => t.name.startsWith(`${prefix}-`)).map((t) => t.name.slice(prefix.length + 1))

const typeDefs = {
  ColorToken: colors.map((t) => t.name),
  IntentColor: colors.filter((t) => t.intent).map((t) => t.name),
  TextSize: suffixes("text"),
  Radius: suffixes("radius"),
  Shadow: suffixes("shadow"),
  Ease: suffixes("ease"),
  FontFamily: suffixes("font"),
  ThemeName: themes.map((t) => t.name),
}
const types = [
  `// ${HEADER}`,
  "",
  ...Object.entries(typeDefs).map(([name, values]) => `export type ${name} = ${union(values)}`),
  "",
].join("\n")

// tailwind-merge must know custom theme values, or cn("text-display", "text-sm") keeps both.
const twMerge = [
  `// ${HEADER}`,
  "// Custom Tailwind theme values, so tailwind-merge resolves conflicts between token classes.",
  "",
  `export const twMergeTheme = ${JSON.stringify(
    { text: typeDefs.TextSize, radius: typeDefs.Radius, shadow: typeDefs.Shadow, ease: typeDefs.Ease, font: typeDefs.FontFamily },
    null,
    2,
  )}`,
  "",
].join("\n")

// Registry: everything in the `registry` scope ships in one theme item.
const toObject = (tokens, fn) => Object.fromEntries(tokens.map(fn))
const registryTheme = {
  name: THEME_ITEM,
  type: "registry:theme",
  title: "Lanzate Theme",
  description: "Design tokens shared by every Lanzate UI component. Generated from tokens/; do not edit by hand.",
  cssVars: {
    theme: {
      ...toObject(colors.filter((t) => t.scope === "registry"), (t) => [`color-${t.name}`, `var(--${t.name})`]),
      ...toObject(themeVars.filter((t) => t.scope === "registry"), (t) => [t.name, t.value]),
    },
    light: toObject([...colors, ...rootVars].filter((t) => t.scope === "registry"), (t) => [t.name, t.value]),
    dark: toObject(dark.filter((t) => t.scope === "registry"), (t) => [t.name, t.value]),
  },
}
const registry = JSON.parse(await readFile(REGISTRY_JSON, "utf8"))
const index = registry.items.findIndex((item) => item.name === THEME_ITEM)
if (index === -1) registry.items.unshift(registryTheme)
else registry.items[index] = registryTheme

const outputs = [
  [path.join(OUT, "tokens.css"), css],
  [path.join(OUT, "tokens.types.ts"), types],
  [path.join(OUT, "tw-merge.config.ts"), twMerge],
  [REGISTRY_JSON, `${JSON.stringify(registry, null, 2)}\n`],
]

// ── Write or check ──────────────────────────────────────────────────────────
if (process.argv.includes("--check")) {
  const stale = []
  for (const [file, content] of outputs) {
    const current = await readFile(file, "utf8").catch(() => null)
    if (current?.replaceAll("\r\n", "\n") !== content) stale.push(path.relative(ROOT, file))
  }
  if (stale.length) fail(`out of date: ${stale.join(", ")}. Run \`bun run tokens\` and commit the result.`)
  console.log("tokens: outputs are up to date")
} else {
  await mkdir(OUT, { recursive: true })
  for (const [file, content] of outputs) await writeFile(file, content)
  console.log(`tokens: wrote ${outputs.map(([file]) => path.relative(ROOT, file)).join(", ")}`)
}
